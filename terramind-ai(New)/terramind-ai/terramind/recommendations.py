def zone_for(lat: float | None, lon: float | None, marz: str | None = None) -> str:
    if marz in ZONE_BY_MARZ:
        return ZONE_BY_MARZ[marz]
    if lat is None or lon is None:
        return "highland"
    if lat > 40.65 and lon > 44.3:
        return "humid_forest"
    if lat < 40.25:
        return "arid_south"
    return "highland"


