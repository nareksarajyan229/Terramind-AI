def recommend(issues: dict, lat: float | None = None, lon: float | None = None,
              marz: str | None = None, min_severity: float = 15.0) -> dict:
    """Վերադարձնում է {"actions": [...], "zone": {...}, "summary": str}։"""
    actions: list[Action] = []
    for key, info in sorted(issues.items(), key=lambda kv: -kv[1].get("severity", 0)):
        sev = float(info.get("severity", 0))
        if sev < min_severity:
            continue
        actions.extend(a for thr, a in RULES.get(key, []) if sev >= thr)

    order = {p: i for i, p in enumerate(PRIORITIES)}
    actions.sort(key=lambda a: order[a.priority])
    zone_key = zone_for(lat, lon, marz)
    zone = SPECIES_BY_ZONE[zone_key]
    top = [k for k, v in issues.items() if v.get("severity", 0) >= min_severity]
    summary = ("Էական խնդիրներ չեն հայտնաբերվել․ շարունակեք պարբերական մշտադիտարկումը յուրաքանչյուր սեզոն։"
               if not top else
               f"{len(actions)} գործողություն՝ {', '.join(ISSUE_NAMES.get(t, t) for t in top)} խնդիրների համար։ "
               f"Սկսեք «Անհապաղ» կետերից, ապա անցեք վերականգնողական աշխատանքներին։")
    return {"actions": [a.to_dict() for a in actions], "zone": {"key": zone_key, **zone}, "summary": summary}


def to_markdown(plan: dict, title: str = "TerraMind AI — Վերականգնման ծրագիր") -> str:
    lines = [f"# {title}", "", plan["summary"], ""]
    for phase in PHASES:
        items = [a for a in plan["actions"] if a["phase"] == phase]
        if not items:
            continue
        lines += [f"## {phase}", ""]
        for a in items:
            lines += [f"### {a['title']}  ({a['priority']}, արժեք {a['cost']})",
                      a["detail"], f"- **Ցուցանիշ․** {a['kpi']}", f"- **Գործընկերներ․** {a['partners']}", ""]
    z = plan["zone"]
    lines += [f"## Առաջարկվող տեղական տեսակներ — {z['label']}", "",
              "| Անվանում | Լատիներեն | Կիրառում |", "|---|---|---|"]
    lines += [f"| {c} | *{l}* | {u} |" for c, l, u in z["species"]]
    return "\n".join(lines)
